package database

import (
	"context"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgtype"
)

// Tenant context for PostgreSQL row-level security (ADR-0010, owner decisions RLS-1 and RLS-2;
// AGENTS.md §10.7). Every tenant-owned table has the policy
//
//	tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid
//
// so a query sees and writes only the rows of the tenant stored in the setting app.tenant_id, and
// no rows at all when the setting is missing or empty. InTenantTx is the only code that sets it.

// TenantSetting is the PostgreSQL setting read by the row-level security policies.
const TenantSetting = "app.tenant_id"

// ErrInvalidTenantID is returned by InTenantTx, before any SQL runs, when the tenant ID is the nil
// UUID or not an RFC 9562 UUID (variant bits 10, version 1 to 8).
var ErrInvalidTenantID = errors.New("invalid tenant ID")

// InTenantTx runs fn in a transaction whose first statement sets app.tenant_id to tenantID with
// set_config(..., is_local => true). The setting therefore belongs to this transaction only: it is
// discarded at commit or rollback, so it never survives on the pooled connection and never leaks
// to the next user of that connection. A session-level setting is never used.
//
// All tenant-scoped queries MUST run through the pgx.Tx passed to fn (for sqlc code:
// sqlcgen.New(tx)). Queries through the pool, or through any other connection, are outside the
// transaction and run without tenant context; row-level security then returns no tenant rows.
//
// It commits if fn returns nil, and rolls back if fn returns an error or panics (the panic is
// re-raised). The tenant ID is validated in Go, before a connection is acquired. Like InTx, keep
// transactions short and never call external services from fn (AGENTS.md §7.8).
//
// tenantID must come from the authenticated principal, never from user input (AGENTS.md §6.3).
// Row-level security is defense in depth: tenant-scoped repositories still filter by tenant_id.
func (db *DB) InTenantTx(ctx context.Context, tenantID [16]byte, fn func(tx pgx.Tx) error) error {
	if err := ValidateTenantID(tenantID); err != nil {
		return err
	}
	return pgx.BeginFunc(ctx, db.pool, func(tx pgx.Tx) error {
		// set_config with a bound parameter (SET LOCAL cannot take one, and building the value into
		// the SQL text would be injection-prone); ::uuid::text stores the canonical lower-case form.
		if _, err := tx.Exec(ctx, `SELECT set_config('`+TenantSetting+`', $1::uuid::text, true)`,
			pgtype.UUID{Bytes: tenantID, Valid: true}); err != nil {
			return fmt.Errorf("set tenant context: %w", err)
		}
		return fn(tx)
	})
}

// ValidateTenantID returns ErrInvalidTenantID unless id is a non-nil RFC 9562 UUID: variant bits
// 10 and a version from 1 to 8. Tenant IDs are generated by PostgreSQL's uuidv7(), so every real
// tenant ID passes.
func ValidateTenantID(id [16]byte) error {
	if id == ([16]byte{}) {
		return fmt.Errorf("%w: the nil UUID is not a tenant", ErrInvalidTenantID)
	}
	if id[8]&0xc0 != 0x80 {
		return fmt.Errorf("%w: not an RFC 9562 UUID (variant)", ErrInvalidTenantID)
	}
	if v := id[6] >> 4; v < 1 || v > 8 {
		return fmt.Errorf("%w: not an RFC 9562 UUID (version %d)", ErrInvalidTenantID, v)
	}
	return nil
}
