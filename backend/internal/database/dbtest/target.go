// Package dbtest gives integration tests an isolated, throwaway PostgreSQL database.
//
// Integration tests (build tag "integration") call NewDatabase, which creates a new database named
// sms_test_<random> and drops it when the test ends, whether it passed or failed. The configured
// DB_NAME is used only to connect to the server; it is never modified or dropped.
//
// Because the helper creates and drops databases, it fails closed: TargetConfig refuses to proceed
// unless the environment is explicitly a local test setup (APP_ENV=test and a loopback DB_HOST).
// The safeguards in this file are compiled in every build so that they are covered by ordinary unit
// tests; the database-creating helpers are compiled only with the "integration" tag.
package dbtest

import (
	"errors"
	"fmt"
	"strings"

	"github.com/hruizjr/sms/backend/internal/config"
)

// NamePrefix starts the name of every database created by this package. Only databases with this
// prefix are ever dropped.
const NamePrefix = "sms_test_"

// ErrUnsafeTarget is returned when the environment is not an explicit, local test setup.
var ErrUnsafeTarget = errors.New("refusing to create integration-test databases")

// TargetConfig returns the database settings for integration tests, read through lookup, after
// checking that they point at a local test server:
//
//   - APP_ENV must be set explicitly to "test". Missing, "development", "production", or any other
//     value is refused (the general configuration would default a missing APP_ENV to development).
//   - The configuration must be valid (config.Load). Its errors never contain the password.
//   - DB_HOST must be a loopback IP literal (127.0.0.0/8 or ::1). Host names, including "localhost",
//     are refused because they are not resolved here and could point anywhere.
func TargetConfig(lookup config.LookupFunc) (config.DatabaseConfig, error) {
	appEnv, ok := config.ExplicitEnvironment(lookup)
	if !ok {
		return config.DatabaseConfig{}, fmt.Errorf("%w: %s is not set; integration tests require %s=test",
			ErrUnsafeTarget, config.EnvAppEnv, config.EnvAppEnv)
	}
	if appEnv != config.EnvironmentTest {
		return config.DatabaseConfig{}, fmt.Errorf("%w: %s=%q; integration tests require %s=test",
			ErrUnsafeTarget, config.EnvAppEnv, string(appEnv), config.EnvAppEnv)
	}

	cfg, err := config.Load(lookup)
	if err != nil {
		return config.DatabaseConfig{}, fmt.Errorf("%w: %w", ErrUnsafeTarget, err)
	}
	if !config.IsLoopbackIP(cfg.Database.Host) {
		return config.DatabaseConfig{}, fmt.Errorf("%w: %s=%q is not a loopback IP address; integration tests run "+
			"only against a local server (127.0.0.1 or ::1; host names such as localhost are not accepted)",
			ErrUnsafeTarget, config.EnvDBHost, cfg.Database.Host)
	}
	return cfg.Database, nil
}

// checkDisposableName verifies that name is safe to create and later drop: it was generated by this
// package (NamePrefix followed by lower-case letters, digits, and underscores), fits PostgreSQL's
// identifier limit, and is not the configured maintenance database.
func checkDisposableName(name, maintenanceDB string) error {
	if !strings.HasPrefix(name, NamePrefix) || len(name) == len(NamePrefix) || len(name) > 63 {
		return fmt.Errorf("database name %q is not a generated %s<suffix> name", name, NamePrefix)
	}
	for _, c := range name {
		if (c < 'a' || c > 'z') && (c < '0' || c > '9') && c != '_' {
			return fmt.Errorf("database name %q contains a character outside [a-z0-9_]", name)
		}
	}
	if name == maintenanceDB {
		return fmt.Errorf("database name %q is the configured %s; it is never created or dropped by tests",
			name, config.EnvDBName)
	}
	return nil
}
