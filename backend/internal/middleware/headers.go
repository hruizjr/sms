package middleware

import "net/http"

// SecurityHeaders sets conservative response headers suitable for a JSON API.
//
// Strict-Transport-Security is intentionally not set here: it belongs to the TLS-terminating
// layer, which does not exist yet (deployment is out of Phase 3 scope).
func SecurityHeaders(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		h := w.Header()
		h.Set("X-Content-Type-Options", "nosniff")
		h.Set("Content-Security-Policy", "default-src 'none'; frame-ancestors 'none'")
		h.Set("Referrer-Policy", "no-referrer")
		h.Set("Cache-Control", "no-store")
		next.ServeHTTP(w, r)
	})
}

// LimitRequestBody caps the number of request body bytes a handler can read. Reading past the
// limit returns an error to the handler, which must respond with 413.
func LimitRequestBody(maxBytes int64) func(http.Handler) http.Handler {
	return func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			r.Body = http.MaxBytesReader(w, r.Body, maxBytes)
			next.ServeHTTP(w, r)
		})
	}
}
