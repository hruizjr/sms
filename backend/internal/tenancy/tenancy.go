// Package tenancy is the tenant registry (Phase 4 Group 1; decision log §18).
//
// A tenant is one client business. The registry is platform-owned and global: the tenants table has
// no tenant_id column and no row-level security, because it is the list of tenants rather than data
// belonging to one. Tenant-owned data (later groups) carries tenant_id and is protected by
// row-level security through database.InTenantTx.
//
// This package has no HTTP endpoints, authentication, users or authorization: those are later,
// separately approved groups. Callers are trusted platform code.
package tenancy

import (
	"errors"
	"fmt"
	"strings"
	"time"
	"unicode"
	"unicode/utf8"

	"github.com/jackc/pgx/v5/pgtype"
)

// Status is a tenant's lifecycle state.
type Status string

// Tenant statuses (the CHECK constraint ck_tenants__status allows exactly these).
const (
	// StatusPending: created, not yet activated. Every tenant starts here.
	StatusPending Status = "pending"
	// StatusActive: activated.
	StatusActive Status = "active"
	// StatusSuspended: suspended by the platform; can be reactivated.
	StatusSuspended Status = "suspended"
)

// MaxDisplayNameLength is the longest accepted display name, in characters (Unicode code points).
// It is an engineering bound matching ck_tenants__display_name, not a business rule.
const MaxDisplayNameLength = 200

// Errors returned by the Repository. Database errors are wrapped and returned as they are.
var (
	ErrNotFound           = errors.New("tenant not found")
	ErrInvalidTransition  = errors.New("tenant status transition not allowed")
	ErrInvalidDisplayName = errors.New("invalid tenant display name")
	ErrInvalidID          = errors.New("invalid tenant ID")
	ErrInvalidPageSize    = errors.New("invalid page size")
)

// ID identifies a tenant. Tenant IDs are UUIDv7 values generated by PostgreSQL (uuidv7()); the
// zero value is the nil UUID and identifies no tenant.
type ID [16]byte

// ParseID parses the canonical text form (and the other forms PostgreSQL accepts for uuid).
func ParseID(s string) (ID, error) {
	var u pgtype.UUID
	if err := u.Scan(s); err != nil || !u.Valid {
		return ID{}, fmt.Errorf("%w: %q", ErrInvalidID, s)
	}
	return ID(u.Bytes), nil
}

// String returns the canonical, lower-case text form.
func (id ID) String() string { return pgtype.UUID{Bytes: id, Valid: true}.String() }

// IsZero reports whether id is the nil UUID.
func (id ID) IsZero() bool { return id == ID{} }

// Version returns the UUID version (7 for every ID generated by the database).
func (id ID) Version() int { return int(id[6] >> 4) }

func (id ID) pg() pgtype.UUID { return pgtype.UUID{Bytes: id, Valid: true} }

// Tenant is one registered tenant.
type Tenant struct {
	ID          ID
	DisplayName string
	Status      Status
	CreatedAt   time.Time // UTC
	UpdatedAt   time.Time // UTC
}

// NormalizeDisplayName trims surrounding white space and validates the result: 1 to
// MaxDisplayNameLength characters, valid UTF-8, no control characters. Names are not required to
// be unique.
func NormalizeDisplayName(name string) (string, error) {
	name = strings.TrimSpace(name)
	switch {
	case !utf8.ValidString(name):
		return "", fmt.Errorf("%w: not valid UTF-8", ErrInvalidDisplayName)
	case name == "":
		return "", fmt.Errorf("%w: empty", ErrInvalidDisplayName)
	case utf8.RuneCountInString(name) > MaxDisplayNameLength:
		return "", fmt.Errorf("%w: longer than %d characters", ErrInvalidDisplayName, MaxDisplayNameLength)
	case strings.IndexFunc(name, unicode.IsControl) >= 0:
		return "", fmt.Errorf("%w: contains a control character", ErrInvalidDisplayName)
	}
	return name, nil
}
